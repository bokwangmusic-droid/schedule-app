const FIXED_HOLIDAYS: Record<string, string> = {
  '01-01': '신정',
  '03-01': '삼일절',
  '05-05': '어린이날',
  '06-06': '현충일',
  '08-15': '광복절',
  '10-03': '개천절',
  '10-09': '한글날',
  '12-25': '성탄절',
};

export function getKoreanHoliday(dateString: string): KoreanHoliday | null {
  const exact = HOLIDAYS[dateString];
  if (exact) return exact;

  const year = Number(dateString.slice(0, 4));
  const monthDay = dateString.slice(5);

  if (year >= 2026 && monthDay === '05-01') return { name: '노동절' };
  if (year >= 2026 && monthDay === '07-17') return { name: '제헌절' };

  const fixed = FIXED_HOLIDAYS[monthDay];
  return fixed ? { name: fixed } : null;
}
